#!/usr/bin/env node
/**
 * Small evidence binder for the isolated signed-JSON manuscript.
 *
 * It intentionally does not replay experiments: E12 is networked and the raw
 * E12/E13/E16 reports are not part of the released tag. Instead, it binds the
 * paper's generated macros to documented anchors in evidence-v1, checks that
 * frozen tags still resolve as declared, and rejects citation-key or macro
 * drift. This is a reviewer aid, not a claim of independent verification.
 */

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST_RELATIVE = "docs/paper-next/evidence-manifest.v1.json";
const MANIFEST_PATH = resolve(ROOT, MANIFEST_RELATIVE);
const MACROS_RELATIVE = "docs/paper-next/evidence-macros.tex";
const TEX_RELATIVE = "docs/paper-next/main.tex";
const BIB_RELATIVE = "docs/paper-next/references.bib";

function fail(message) {
  throw new Error(`paper-next-evidence: ${message}`);
}

function read(relative) {
  return readFileSync(resolve(ROOT, relative), "utf8");
}

function git(args) {
  return execFileSync("git", ["-C", ROOT, ...args], { encoding: "utf8" }).trim();
}

function assertString(value, name) {
  if (typeof value !== "string" || value.length === 0) fail(`${name} must be a non-empty string.`);
  return value;
}

function assertInteger(value, name) {
  if (!Number.isInteger(value) || value < 0) fail(`${name} must be a non-negative integer.`);
  return value;
}

function loadManifest() {
  const manifest = JSON.parse(read(MANIFEST_RELATIVE));
  if (manifest.schema_version !== "ghost-ark.paper-next-evidence.v1") fail("unsupported schema version.");
  assertString(manifest.paper?.title, "paper.title");
  assertString(manifest.paper?.question, "paper.question");
  assertString(manifest.paper?.non_claim, "paper.non_claim");
  for (const key of ["evidence_tag", "evidence_revision", "release_tag", "release_revision"]) {
    assertString(manifest.frozen_inputs?.[key], `frozen_inputs.${key}`);
  }
  if (!Array.isArray(manifest.findings) || manifest.findings.length < 6) fail("at least six findings are required.");
  for (const finding of manifest.findings) {
    assertString(finding.id, "finding.id");
    assertString(finding.source, `finding ${finding.id} source`);
    assertString(finding.anchor, `finding ${finding.id} anchor`);
    assertString(finding.command, `finding ${finding.id} command`);
    if (!finding.values || typeof finding.values !== "object") fail(`finding ${finding.id} must include values.`);
  }
  if (!Array.isArray(manifest.required_citation_keys) || manifest.required_citation_keys.length < 8) {
    fail("the manuscript must declare its core literature keys.");
  }
  return manifest;
}

function format(value) {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/gu, "{,}");
}

function byId(manifest, id) {
  const finding = manifest.findings.find((entry) => entry.id === id);
  if (!finding) fail(`missing finding ${id}.`);
  return finding;
}

function renderMacros(manifest) {
  const e1 = byId(manifest, "e1").values;
  const e1b = byId(manifest, "e1b").values;
  const e7 = byId(manifest, "e7").values;
  const e11 = byId(manifest, "e11").values;
  const e12 = byId(manifest, "e12").values;
  const e13 = byId(manifest, "e13").values;
  const e16 = byId(manifest, "e16").values;
  return [
    "% This file is generated by tools/paper-next-evidence.mjs from evidence-manifest.v1.json.",
    "% Do not edit it by hand; run: node tools/paper-next-evidence.mjs --render",
    "% Values are evidence-record anchors, not population estimates unless stated in the manuscript.",
    `\\newcommand{\\pnEOneClasses}{${e1.classes}}`,
    `\\newcommand{\\pnEOneUnguarded}{${e1.unguarded_unintended}}`,
    `\\newcommand{\\pnEOneStrict}{${e1.strict_unintended}}`,
    `\\newcommand{\\pnEOneStrictAsymmetry}{${e1.strict_rejection_asymmetry}}`,
    `\\newcommand{\\pnEOneBSuccesses}{${e1b.unguarded_successes}}`,
    `\\newcommand{\\pnEOneBDenominator}{${e1b.denominator}}`,
    `\\newcommand{\\pnEOneBRate}{${e1b.unguarded_rate_percent}\\%}`,
    `\\newcommand{\\pnEOneBInterval}{${e1b.unguarded_interval.replaceAll("%", "\\%")}}`,
    `\\newcommand{\\pnEOneBStrictRate}{${e1b.strict_rate_percent.toFixed(1)}\\%}`,
    `\\newcommand{\\pnEOneBStrictInterval}{${e1b.strict_interval.replaceAll("%", "\\%")}}`,
    `\\newcommand{\\pnESevenInputs}{${format(e7.inputs)}}`,
    `\\newcommand{\\pnESevenClasses}{${e7.structural_classes}}`,
    `\\newcommand{\\pnESevenMechanisms}{${e7.underlying_mechanisms}}`,
    `\\newcommand{\\pnEElevenArms}{${e11.third_party_arms}}`,
    `\\newcommand{\\pnEElevenClasses}{${e11.classes}}`,
    `\\newcommand{\\pnEElevenUnintended}{${e11.unintended_per_arm}}`,
    `\\newcommand{\\pnEElevenDuplicates}{${e11.universal_duplicate_classes}}`,
    `\\newcommand{\\pnETwelveDraws}{${format(e12.draws)}}`,
    `\\newcommand{\\pnETwelveEligible}{${e12.eligible_payloads}}`,
    `\\newcommand{\\pnETwelveObserved}{${e12.observed_pathologies}}`,
    `\\newcommand{\\pnETwelveProducers}{${e12.producers}}`,
    `\\newcommand{\\pnETwelveControls}{${e12.detector_controls}}`,
    `\\newcommand{\\pnEThirteenForward}{${e13.real_forward_counterexamples}}`,
    `\\newcommand{\\pnEThirteenRepairsBySeparation}{${e13.repairs_by_separation}}`,
    `\\newcommand{\\pnESixteenEngines}{${e16.engines}}`,
    `\\newcommand{\\pnESixteenCells}{${e16.decision_split_cells}}`,
    "",
  ].join("\n");
}

function assertFrozenInputs(manifest) {
  const evidence = git(["rev-parse", `${manifest.frozen_inputs.evidence_tag}^{}`]);
  const release = git(["rev-parse", `${manifest.frozen_inputs.release_tag}^{}`]);
  if (evidence !== manifest.frozen_inputs.evidence_revision) fail("evidence tag no longer resolves to the declared revision.");
  if (release !== manifest.frozen_inputs.release_revision) fail("release tag no longer resolves to the declared revision.");
}

function showAtEvidenceRevision(manifest, relative) {
  return execFileSync("git", ["-C", ROOT, "show", `${manifest.frozen_inputs.evidence_revision}:${relative}`], { encoding: "utf8" });
}

function assertSourceAnchors(manifest) {
  for (const finding of manifest.findings) {
    if (!existsSync(resolve(ROOT, finding.source))) fail(`missing current source ${finding.source}.`);
    const frozen = showAtEvidenceRevision(manifest, finding.source);
    if (!frozen.includes(finding.anchor)) {
      fail(`${finding.id} anchor is absent from frozen evidence: ${finding.anchor}`);
    }
  }
}

function citationKeys(tex) {
  const keys = new Set();
  for (const match of tex.matchAll(/\\cite\{([^}]+)\}/gu)) {
    for (const key of match[1].split(",").map((entry) => entry.trim()).filter(Boolean)) keys.add(key);
  }
  return keys;
}

function bibliographyKeys(bib) {
  return new Set([...bib.matchAll(/@\w+\s*\{\s*([^,\s]+)/gu)].map((match) => match[1]));
}

function assertCitationIntegrity(manifest) {
  if (!existsSync(resolve(ROOT, TEX_RELATIVE))) fail(`${TEX_RELATIVE} is missing.`);
  if (!existsSync(resolve(ROOT, BIB_RELATIVE))) fail(`${BIB_RELATIVE} is missing.`);
  const tex = read(TEX_RELATIVE);
  const cited = citationKeys(tex);
  const defined = bibliographyKeys(read(BIB_RELATIVE));
  for (const key of cited) if (!defined.has(key)) fail(`citation key ${key} has no bibliography entry.`);
  for (const key of manifest.required_citation_keys) {
    if (!cited.has(key)) fail(`required citation key ${key} is not cited in the manuscript.`);
    if (!defined.has(key)) fail(`required citation key ${key} is absent from the bibliography.`);
  }
}

function assertGenerated(manifest) {
  const expected = renderMacros(manifest);
  if (!existsSync(resolve(ROOT, MACROS_RELATIVE))) fail(`${MACROS_RELATIVE} is missing.`);
  if (read(MACROS_RELATIVE) !== expected) fail(`generated macros are stale; run node tools/paper-next-evidence.mjs --render.`);
  const tex = read(TEX_RELATIVE);
  if (!tex.includes("\\input{evidence-macros.tex}")) fail("manuscript does not load generated evidence macros.");
  for (const macro of ["pnEOneClasses", "pnEElevenArms", "pnETwelveEligible", "pnESixteenCells"]) {
    if (!tex.includes(`\\${macro}`)) fail(`manuscript does not use required macro ${macro}.`);
  }
}

function check() {
  const manifest = loadManifest();
  assertFrozenInputs(manifest);
  assertSourceAnchors(manifest);
  assertGenerated(manifest);
  assertCitationIntegrity(manifest);
  return manifest;
}

function main(args = process.argv.slice(2)) {
  if (args.length !== 1 || !new Set(["--check", "--render"]).has(args[0])) {
    process.stderr.write("Usage: node tools/paper-next-evidence.mjs --check | --render\n");
    return 1;
  }
  const manifest = loadManifest();
  if (args[0] === "--render") {
    writeFileSync(resolve(ROOT, MACROS_RELATIVE), renderMacros(manifest), "utf8");
    process.stdout.write("paper-next-evidence: rendered macros.\n");
    return 0;
  }
  check();
  process.stdout.write("paper-next-evidence: frozen anchors, macros, and citations are in sync.\n");
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}

export { check, loadManifest, main, renderMacros };
